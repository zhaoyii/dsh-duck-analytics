/**
 * Build the browser bundle for this plugin.
 *
 * The DSH client module system loads a plugin as `factory(require)`, not as an ES
 * module, so this step concatenates three things into one file:
 *
 * 1. the `window.__ModuleLoader__.load({ id, factory })` envelope, with `id`
 *    equal to the package name the Host resolved from this package's manifest;
 * 2. the vendored ECharts build, evaluated into a local `__echarts` binding (its
 *    UMD wrapper takes the CommonJS branch because `module`/`exports` exist);
 * 3. the authored bundle body (`src/client/index.js`), which reads that binding.
 *
 * ECharts is inlined rather than requested from the shared module table: it is a
 * third-party implementation library outside the client baseline, which the
 * client authoring rules allow a plugin to carry privately.
 *
 * @module scripts/build-client
 */
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'

/** Repository root of this plugin package. */
const root = path.resolve(import.meta.dirname, '..')

/** Authored bundle body. */
const BODY = path.join(root, 'src/client/index.js')

/**
 * Vendored ECharts build.
 *
 * `common` rather than `simple`: the card is interactive, which needs the
 * `dataZoom`, `toolbox`, and `brush` components that only this build registers
 * (`simple` carries their option names but not their implementations).
 */
const ECHARTS = path.join(root, 'node_modules/echarts/dist/echarts.common.min.js')

/** Emitted bundle the Host serves for this package's `./client` export. */
const OUT = path.join(root, 'lib/client.js')

/**
 * Wrap one CommonJS body so it evaluates into its own `module.exports`.
 * @param source - JavaScript evaluated with `module`/`exports` in scope.
 * @returns an expression yielding that module's exports.
 */
function isolate(source) {
  return `(function(){var module={exports:{}};var exports=module.exports;${source}\nreturn module.exports})()`
}

const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
if (typeof manifest.name !== 'string' || manifest.name === '') {
  throw new Error('package.json must declare a name: the bundle id is the package name')
}

const [body, echarts] = await Promise.all([readFile(BODY, 'utf8'), readFile(ECHARTS, 'utf8')])

const bundle = [
  '// Generated by scripts/build-client.mjs — edit src/client/index.js instead.',
  `window.__ModuleLoader__.load({id:\`${manifest.name}\`,factory:require=>{`,
  'var module={exports:{}};var exports=module.exports;',
  'Object.defineProperty(exports,Symbol.toStringTag,{value:`Module`});',
  `var __echarts=${isolate(echarts)};`,
  body,
  '\nreturn module.exports}})',
  '',
].join('\n')

await mkdir(path.dirname(OUT), { recursive: true })
await writeFile(OUT, bundle, 'utf8')
const { size } = await stat(OUT)
process.stdout.write(`wrote ${path.relative(root, OUT)} (${(size / 1024).toFixed(0)} KiB)\n`)
